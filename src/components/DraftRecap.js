export function attachDraftRecapEvents(container) {
  const modal = container.querySelector('#team-strengths-modal');
  const title = container.querySelector('#ts-modal-title');
  const sub = container.querySelector('#ts-modal-sub');
  const body = container.querySelector('#ts-modal-body');
  const btnClose = container.querySelector('#btn-close-ts-modal');
  const btnGotIt = container.querySelector('#btn-ts-got-it');

  function openTeamDetail(rosterId) {
    const data = TEAM_LINEUP_STRENGTHS[rosterId];
    if (!data || !modal) return;

    title.textContent = '📊 Fuerza de Alineación • ' + data.teamName;
    sub.textContent = 'Calificación de Draft: ' + data.gradeLetter + ' (' + data.scoreNum + ')';
    body.innerHTML = renderTeamDetailModalContent(rosterId);

    modal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
  }

  function closeModal() {
    if (!modal) return;
    modal.style.display = 'none';
    document.body.style.overflow = '';
  }

  container.querySelectorAll('.clickable-team-detail').forEach(el => {
    el.addEventListener('click', (e) => {
      e.stopPropagation();
      const rosterId = el.getAttribute('data-roster-id');
      if (rosterId) openTeamDetail(rosterId);
    });
  });

  btnClose?.addEventListener('click', closeModal);
  btnGotIt?.addEventListener('click', closeModal);
  modal?.addEventListener('click', (e) => {
    if (e.target === modal) closeModal();
  });
}
